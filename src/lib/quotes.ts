/* --------------------------------------------- live extras from QuotesDB */

const EXTRA_KEY = 'floe-quotes-extra'
const ALLOWED = new Set(['Motivation', 'Motivational', 'Inspiration', 'Inspirational', 'Success', 'Courage', 'Strength', 'Dreams', 'Hope'])

export function extraQuotes(): Quote[] {
  try { return JSON.parse(localStorage.getItem(EXTRA_KEY) ?? '[]') } catch { return [] }
}

/** Pulls a few quotes from quotes-db.vercel.app in the background; failures are silent. */
export async function refreshExtraQuotes(count = 6) {
  const have = extraQuotes()
  const seen = new Set([...QUOTES, ...have].map((q) => q.text.toLowerCase()))
  const fresh: Quote[] = []
  for (let i = 0; i < count; i++) {
    try {
      const r = await fetch(`https://quotes-db.vercel.app/api/random?t=${Date.now()}-${i}`, { signal: AbortSignal.timeout(6000) })
      if (!r.ok) break
      const q = (await r.json()) as { quote?: string; author?: string; category?: string }
      const text = q.quote?.trim()
      if (!text || text.length > 160 || !ALLOWED.has(q.category ?? '') || seen.has(text.toLowerCase())) continue
      seen.add(text.toLowerCase())
      fresh.push({ text, author: q.author?.trim() || 'Unknown' })
    } catch { break }
  }
  if (fresh.length) {
    try { localStorage.setItem(EXTRA_KEY, JSON.stringify([...have, ...fresh].slice(-500))) } catch { /* storage full */ }
  }
}
